/* =========================================================
   PROJECT MODAL
   ========================================================= */

function openProject(id) {
  const project = projects[id];

  if (!project) {
    return;
  }

  let html = `
    <article class="detail">
      <div class="detail-kicker">${project.kicker}</div>

      <h2>${project.title}</h2>

      <p class="intro">
        ${project.intro}
      </p>

      <div class="detail-grid">
        ${project.blocks
          .map(
            (block) => `
              <div class="detail-block">
                <h3>${block[0]}</h3>

                <p>
                  <b>${block[1]}</b>
                </p>

                <p>
                  ${block[2]}
                </p>
              </div>
            `
          )
          .join('')}
      </div>
  `;


  /* ---------------------------------------------------------
     WORKSPACE LINKS
     --------------------------------------------------------- */

  if (project.links) {
    html += `
      <div class="media">
        <h3>WORKSPACE LINKS</h3>

        <div class="doc-links">
          ${project.links
            .map(
              (link) => `
                <a
                  href="${link[1]}"
                  target="_blank"
                  rel="noopener noreferrer"
                >
                  ${link[0]} ↗
                </a>
              `
            )
            .join('')}
        </div>
      </div>
    `;
  }


  /* ---------------------------------------------------------
     DOCUMENTATION
     --------------------------------------------------------- */

  if (project.docs) {
    html += `
      <div class="media">
        <h3>DOCUMENTATION</h3>

        <div class="doc-links">
          ${project.docs
            .map(
              (link) => `
                <a
                  href="${link[1]}"
                  target="_blank"
                  rel="noopener noreferrer"
                >
                  ${link[0]} ↗
                </a>
              `
            )
            .join('')}
        </div>
      </div>
    `;
  }


  /* ---------------------------------------------------------
     GDD / GAME DESIGN DOCUMENT
     --------------------------------------------------------- */

  if (project.gdd) {
    html += `
      <div class="media gdd-section">
        <h3>${project.gdd_title}</h3>

        <div class="doc-links">
          <a
            class="gdd-link"
            href="${project.gdd}"
            target="_blank"
            rel="noopener noreferrer"
          >
            ${project.doc_button_text} ↗
          </a>
        </div>
      </div>
    `;
  }


  /* ---------------------------------------------------------
     PROJECT MEDIA + GAMEPLAY EVIDENCE
     --------------------------------------------------------- */

  const hasMedia = project.media?.length;
  const hasGameplayImages = project.images?.length;

  if (hasMedia || hasGameplayImages) {
    html += `
      <div class="detail-lower">
        <div class="detail-media-column">
    `;

    /* -------------------------------------------------------
       PROJECT MEDIA / VIDEOS
       ------------------------------------------------------- */

    if (hasMedia) {
      html += `
        <div class="media">
          <h3>PROJECT MEDIA</h3>

          <div class="two-media">
            ${project.media
              .map(
                (media) => `
                  <div>
                    <div class="video-info">
                      <h4 class="video-title">
                        ${media[2]}
                      </h4>

                      <p class="video-description">
                        ${media[3]}
                      </p>
                    </div>

                    <video
                      controls
                      preload="metadata"
                    >
                      <source
                        src="${media[1]}"
                        type="video/mp4"
                      >

                      Your browser does not support HTML5 video.
                    </video>
                  </div>
                `
              )
              .join('')}
          </div>
        </div>
      `;
    }

    html += `
        </div>

        <aside class="gameplay-evidence">
    `;

    /* -------------------------------------------------------
       GAMEPLAY EVIDENCE CAROUSEL
       ------------------------------------------------------- */

    if (hasGameplayImages) {
      html += `
          <div class="gameplay-evidence-header">
            <div>
              <span class="gameplay-kicker">
                VISUAL EVIDENCE
              </span>

              <h3>GAMEPLAY EVIDENCE</h3>
            </div>

            <span class="gameplay-count">
              01 / ${String(project.images.length).padStart(2, '0')}
            </span>
          </div>

          <div
            class="gameplay-carousel"
            data-carousel
            data-project="${project.title}"
          >
            <div class="gameplay-stage">
              <img
                class="gameplay-slide"
                src="${project.images[0]}"
                alt="${project.title} gameplay screenshot 1"
                data-slide-image
              >

              <button
                class="gameplay-arrow gameplay-prev"
                type="button"
                aria-label="Previous gameplay screenshot"
                data-carousel-prev
              >
                ←
              </button>

              <button
                class="gameplay-arrow gameplay-next"
                type="button"
                aria-label="Next gameplay screenshot"
                data-carousel-next
              >
                →
              </button>
            </div>

            <div class="gameplay-progress">
              <span data-carousel-progress>
                01 / ${String(project.images.length).padStart(2, '0')}
              </span>

              <span>
                USE ARROWS TO EXPLORE
              </span>
            </div>
          </div>
      `;
    }

    html += `
        </aside>
      </div>
    `;
  }


  html += `
    </article>
  `;


  /* ---------------------------------------------------------
     INSERT CONTENT + OPEN MODAL
     --------------------------------------------------------- */

  const modalContent = document.getElementById('modalContent');
  const projectModal = document.getElementById('projectModal');

  if (!modalContent || !projectModal) {
    return;
  }

  modalContent.innerHTML = html;

  /* ---------------------------------------------------------
     INITIALIZE GAMEPLAY IMAGE CAROUSEL
     --------------------------------------------------------- */

  document
    .querySelectorAll('[data-carousel]')
    .forEach((carousel) => {
      const images = project.images || [];

      if (!images.length) {
        return;
      }

      let currentIndex = 0;

      const imageElement =
        carousel.querySelector('[data-slide-image]');

      const progressElement =
        carousel.querySelector('[data-carousel-progress]');

      const countElement =
        carousel
          .closest('.gameplay-evidence')
          ?.querySelector('.gameplay-count');

      const updateCarousel = () => {
        const displayIndex = currentIndex + 1;
        const formattedIndex = String(displayIndex).padStart(2, '0');
        const formattedTotal = String(images.length).padStart(2, '0');

        imageElement.src = images[currentIndex];

        imageElement.alt =
          `${project.title} gameplay screenshot ${displayIndex}`;

        const progressText =
          `${formattedIndex} / ${formattedTotal}`;

        if (progressElement) {
          progressElement.textContent = progressText;
        }

        if (countElement) {
          countElement.textContent = progressText;
        }
      };

      carousel
        .querySelector('[data-carousel-prev]')
        ?.addEventListener('click', () => {
          currentIndex =
            (currentIndex - 1 + images.length) %
            images.length;

          updateCarousel();
        });

      carousel
        .querySelector('[data-carousel-next]')
        ?.addEventListener('click', () => {
          currentIndex =
            (currentIndex + 1) %
            images.length;

          updateCarousel();
        });

      updateCarousel();
    });


  projectModal.classList.remove('hidden');

  document.body.style.overflow = 'hidden';
}


/* =========================================================
   PROJECT BUTTON EVENTS
   ========================================================= */

document.querySelectorAll('[data-open]').forEach((button) => {
  button.addEventListener('click', (event) => {
    event.stopPropagation();

    openProject(button.dataset.open);
  });
});


/* =========================================================
   PROJECT MODAL CLOSE
   ========================================================= */

const modalClose = document.querySelector('.modal-close');

if (modalClose) {
  modalClose.onclick = () => {
    const projectModal = document.getElementById('projectModal');

    if (projectModal) {
      projectModal.classList.add('hidden');
    }

    document.body.style.overflow = '';
  };
}


const projectModal = document.getElementById('projectModal');

if (projectModal) {
  projectModal.addEventListener('click', (event) => {
    if (event.target.id === 'projectModal') {
      if (modalClose) {
        modalClose.click();
      }
    }
  });
}


